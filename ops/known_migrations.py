"""Generate store/migrations/known_migrations.py from the repository history.

Every migration file any commit reachable from HEAD ever had is listed with the checksum the runner records for it
(md5 of the text as Path.read_text gives it) and what it is today:
- current:     today's file, today's content;
- earlier:     today's file (same number and name), earlier content - the runner never re-runs an applied file;
- renumbered:  the same content as today's file under another number (the two lines numbered in parallel);
- superseded:  a migration no file today stands for (an earlier mainline numbering); a database that recorded it
               needs a person to decide, the runner refuses it.

    python ops/known_migrations.py           # print the module
    python ops/known_migrations.py --check   # exit 1 if store/migrations/known_migrations.py is out of date
"""

import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSIONS = ROOT / "store" / "migrations" / "versions"
TARGET = ROOT / "store" / "migrations" / "known_migrations.py"
# where the files are, and where they were before r1 moved migration/ into store/: the history is read from both
HISTORY_DIRS = ("store/migrations/versions/", "migration/versions/")


def _git(*args):
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, check=True).stdout


def _checksum(text):
    return hashlib.md5(text.encode()).hexdigest()


def _key(name):
    stem = name[:-4]  # drop .sql
    version, _, rest = stem.partition("__")
    return version, rest.replace("_", " ")


def entries():
    current = {}
    for path in sorted(VERSIONS.glob("V*.sql")):
        current[path.name] = _checksum(path.read_text(encoding="utf-8"))
    by_checksum = {checksum: name for name, checksum in current.items()}
    seen = {}
    for commit in _git("rev-list", "HEAD", "--", *HISTORY_DIRS).decode().split():
        for folder in HISTORY_DIRS:
            for line in _git("ls-tree", commit, folder).decode().splitlines():
                _mode, _type, blob, path = line.split(None, 3)
                name = path.rsplit("/", 1)[1]
                if not (name.startswith("V") and name.endswith(".sql")):
                    continue
                text = _git("cat-file", "-p", blob).decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
                seen.setdefault((name, _checksum(text)), commit[:7])
    for name, checksum in current.items():
        seen.setdefault((name, checksum), "HEAD")
    rows = []
    for (name, checksum), commit in sorted(seen.items()):
        version, description = _key(name)
        if current.get(name) == checksum:
            kind, target = "current", name
        elif name in current:
            kind, target = "earlier", name
        elif checksum in by_checksum:
            kind, target = "renumbered", by_checksum[checksum]
        else:
            kind, target = "superseded", None
        rows.append((version, description, checksum, kind, target, commit))
    return rows


def render():
    lines = [
        "# ruff: noqa: E501 - generated data, one migration per line",
        '"""Every migration a commit of this repository ever recorded, by (version, description, checksum).',
        "",
        "Generated by ops/known_migrations.py from the repository history; do not edit by hand.",
        "kind: current / earlier (today's file, earlier content) / renumbered (today's content under another number) /",
        'superseded (no file today stands for it). seen: a commit that had it."""',
        "",
        "KNOWN = (",
        "    # (version, description, checksum, kind, file today, seen)",
    ]
    for row in entries():
        lines.append(f"    {row!r},")
    lines.append(")")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if TARGET.read_text(encoding="utf-8") != text:
            print("store/migrations/known_migrations.py is out of date: python ops/known_migrations.py > "
                  "store/migrations/known_migrations.py")
            sys.exit(1)
        print("store/migrations/known_migrations.py is up to date")
    else:
        sys.stdout.write(text)
