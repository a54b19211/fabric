"""Trial attributes remain bound to the frozen source field values."""
import json
from datetime import datetime, timezone
from pathlib import Path

import pytest

from biz_rules.history_models import AvailabilityProof, HistoryError, HistoryRecord, sha256
from biz_rules.native_graph import build_native_graph, validate_field_bindings
from biz_rules.reviewed_graph import GraphBundle


def record():
    raw = json.dumps({"protocolSection": {
        "identificationModule": {"nctId": "NCT00000001", "briefTitle": "Title"},
        "designModule": {"phases": ["PHASE2"]},
        "statusModule": {"overallStatus": "TERMINATED", "startDateStruct": {"date": "2020-04", "type": "ESTIMATED"}},
        "conditionsModule": {"conditions": ["Condition A"]},
    }})
    now = datetime(2026, 10, 31, tzinfo=timezone.utc)
    return HistoryRecord(source_id="clinicaltrials", source_record_id="NCT00000001", record_kind="trial",
                         version_id=sha256("fixed:" + raw), raw_content=raw, raw_sha256=sha256(raw),
                         title="Title", clean_text="Title", is_demo=True, facts={}, field_locators={},
                         first_seen_at=now, received_at=now, published_seq=1,
                         availability_proof=AvailabilityProof(kind="unverified"))


def test_trial_native_graph_retains_original_status_phase_and_date_structure():
    source = record()
    graph = build_native_graph([source])
    trial = next(node for node in graph.nodes if node.entity_type == "ClinicalTrial")
    assert trial.properties["phases"] == ["PHASE2"]
    assert trial.properties["status"] == "TERMINATED"
    assert trial.properties["start_date"] == {"date": "2020-04", "type": "ESTIMATED"}
    assert any(field.json_pointer.endswith("/startDateStruct") for field in trial.field_evidence)
    assert all(node.identity_status == "unresolved" for node in graph.nodes if node != trial)


def test_native_trial_properties_cannot_be_changed_without_matching_source():
    source = record()
    graph = build_native_graph([source])
    trial = next(node for node in graph.nodes if node.entity_type == "ClinicalTrial")
    trial.properties["status"] = "COMPLETED"
    documents = {(source.source_id, source.source_record_id, source.version_id, source.raw_sha256, None): source.model_dump(mode="json")}
    with pytest.raises(HistoryError):
        validate_field_bindings(graph, documents)


def legacy_graph():
    # Generated by, and validated with, the real 82bad7b native_graph implementation.
    fixture = json.loads((Path(__file__).parent / "fixtures/native_graph_v1.json").read_text())
    source = HistoryRecord.model_validate(fixture["record"])
    graph = GraphBundle.model_validate(fixture["graph"])
    documents = {(source.source_id, source.source_record_id, source.version_id,
                  source.raw_sha256, None): source.model_dump(mode="json")}
    return graph, documents


@pytest.mark.parametrize("edge_less", [False, True])
def test_frozen_v1_native_graph_remains_readable_but_cannot_be_newly_published(edge_less):
    graph, documents = legacy_graph()
    if edge_less:
        graph.nodes = [node for node in graph.nodes if node.entity_type == "ClinicalTrial"]
        graph.edges = []
    validate_field_bindings(graph, documents, allow_legacy=True)
    with pytest.raises(HistoryError):
        validate_field_bindings(graph, documents)


@pytest.mark.parametrize("mutation", ["unknown_method", "mixed_method", "trial_properties",
                                     "trial_fields", "child_properties", "collaborator"])
def test_frozen_v1_contract_does_not_accept_new_or_unknown_fields(mutation):
    graph, documents = legacy_graph()
    if mutation == "unknown_method":
        graph.edges[0].relation_props["method_version"] = "clinicaltrials.fields.v0"
    elif mutation == "mixed_method":
        graph.edges.append(graph.edges[0].model_copy(deep=True))
        graph.edges[-1].id += "-different"
        graph.edges[-1].relation_props["method_version"] = "clinicaltrials.fields.v2"
    elif mutation == "trial_properties":
        graph.nodes[0].properties = {"status": "COMPLETED"}
    elif mutation == "trial_fields":
        graph.nodes[0].field_evidence = [graph.nodes[0].identity_rule.basis]
    elif mutation == "child_properties":
        graph.nodes[1].properties = {"confirmed": True}
    else:
        graph.edges[0].relation_type = "REGISTERED_COLLABORATOR"
    with pytest.raises(HistoryError):
        validate_field_bindings(graph, documents, allow_legacy=True)


def test_frozen_read_also_accepts_current_v2_contract():
    source = record()
